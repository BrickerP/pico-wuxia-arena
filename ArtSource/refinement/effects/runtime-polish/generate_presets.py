"""Compile reviewed motion contracts into Kotlin constants; never publish APK assets."""
from pathlib import Path
import json
import hashlib

ROOT = Path(__file__).resolve().parents[4]
HERE = Path(__file__).resolve().parent
OUTPUT = ROOT / 'app/src/main/java/com/example/wuxiaarena/p0d2f0182/content/ContactParticlePresets.kt'
SOURCE = ROOT / 'ArtSource/refinement/effects/contact-polish'
JOBS = [
    ('SOFT', HERE / 'soft/motion.json', 'soft_contact_polish.glb'),
    ('METAL', SOURCE / 'metal/motion.json', 'metal_contact_polish.glb'),
]

def number(x):
    return repr(float(x))

def vec(v):
    return 'Vector3(' + ', '.join(map(number, v)) + ')'

def keys(values):
    assert values and all(0 <= alpha <= 1 for _, alpha in values)
    assert all(a[0] < b[0] for a, b in zip(values, values[1:]))
    return 'listOf(' + ', '.join('OpacityKey(' + number(t) + ', ' + number(a) + 'f)' for t, a in values) + ')'

def main():
    lines = ['package com.example.wuxiaarena.p0d2f0182.content', '',
             'import com.example.wuxiaarena.core.math.Vector3', '',
             '// Generated by ArtSource/refinement/effects/runtime-polish/generate_presets.py.',
             '// Source motion.json owns velocities, opacity and lifetimes. No runtime JSON parsing.',
             'internal val CONTACT_EFFECT_DEFINITIONS = listOf(']
    manifest = []
    for family, path, asset in JOBS:
        raw = path.read_bytes()
        data = json.loads(raw)
        lines += [f'    ContactEffectDefinition(ContactEffectFamily.{family}, "{asset}", listOf(']
        for p in data['particles']:
            lines += ['        ContactParticleDefinition("' + p['node'] + '", ' + vec(p['initial_position_local_m']) + ', ' +
                      vec(p['initial_velocity_local_mps']) + ', ' + number(p['lifetime_s']) + ', ' + keys(p['opacity_keys']) +
                      ', followsVelocity = ' + str(p['type'] == 'metal_spark').lower() +
                      ', grounded = ' + str('GROUND' in family).lower() + '),']
        lines += ['    ), listOf(']
        for c in data.get('cores', []):
            normal = c['normal']['opacity_keys']
            parry = c.get('parry', c['normal'])['opacity_keys']
            lines += ['        ContactCoreDefinition("' + c['node'] + '", ' + vec(c.get('initial_position_local_m', [0,0,0])) + ', ' +
                      keys(normal) + ', ' + keys(parry) + ', directional = ' + str(c['node'] == 'scar').lower() + '),']
        lines += ['    )),']
        glb = path.parent / asset
        manifest.append({'family': family, 'motion': str(path.relative_to(ROOT)),
                         'motion_sha256': hashlib.sha256(raw).hexdigest(), 'candidate': str(glb.relative_to(ROOT)),
                         'asset_sha256': hashlib.sha256(glb.read_bytes()).hexdigest(),
                         'publish_to': 'app/src/main/assets/models/effects/contact-polish/' + asset,
                         'particle_count': len(data['particles']), 'core_count': len(data.get('cores', []))})
    lines += [')', '']
    OUTPUT.write_text('\n'.join(lines))
    (HERE / 'resource_handoff.json').write_text(json.dumps({'publication_owner': 'Root', 'assets': manifest,
        'kotlin': str(OUTPUT.relative_to(ROOT)), 'kotlin_sha256': hashlib.sha256(OUTPUT.read_bytes()).hexdigest()}, indent=2) + '\n')
    print(json.dumps({'output': str(OUTPUT), 'families': len(JOBS), 'assets': manifest}, indent=2))

if __name__ == '__main__':
    main()
